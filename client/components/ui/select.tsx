// Radix はトリガーへフォーカスを戻すとき focus() を呼ぶので、マウスで選んでも Chrome は :focus-visible を当てる
function markPointerFocus() {
  const trigger = document.activeElement;
  if (!(trigger instanceof HTMLElement)) return;
  if (trigger.dataset.slot !== "select-trigger") return;
  trigger.dataset.pointerFocus = "";
  const clear = () => {
    delete trigger.dataset.pointerFocus;
    trigger.removeEventListener("keydown", clear);
    trigger.removeEventListener("blur", clear);
  };
  trigger.addEventListener("keydown", clear);
  trigger.addEventListener("blur", clear);
}

function SelectContent({
  className,
  children,
  position = "popper",
  onPointerUp,
  onPointerDownOutside,
  onKeyDown,
  onCloseAutoFocus,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  const closedByPointerRef = React.useRef(false);
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        data-slot="select-content"
        className={cn(
          "relative z-50 max-h-(--radix-select-content-available-height) min-w-32 origin-(--radix-select-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-popover text-popover-foreground shadow-md ring-1 ring-foreground/10 duration-100 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          position === "popper" &&
            "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className,
        )}
        position={position}
        onPointerUp={(event) => {
          closedByPointerRef.current = true;
          onPointerUp?.(event);
        }}
        onPointerDownOutside={(event) => {
          closedByPointerRef.current = true;
          onPointerDownOutside?.(event);
        }}
        onKeyDown={(event) => {
          closedByPointerRef.current = false;
          onKeyDown?.(event);
        }}
        onCloseAutoFocus={(event) => {
          onCloseAutoFocus?.(event);
          if (closedByPointerRef.current) queueMicrotask(markPointerFocus);
          closedByPointerRef.current = false;
        }}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          className={cn(
            "p-1",
            position === "popper" &&
              "h-(--radix-select-trigger-height) w-full min-w-(--radix-select-trigger-width) scroll-my-1",
          )}
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  );
}

